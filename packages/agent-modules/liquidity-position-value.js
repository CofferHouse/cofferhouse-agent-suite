import { readMeteoraPositionReceipt } from "./meteora-position-comparison.js";
import { decimalUnits, decimalText } from "../shared/decimal-usd.js";

export const POSITION_VALUE_WINDOW_SECONDS = 120;
// This is a provider-balance reference, never authenticated investment performance.
export function attachLiquidityPositionValue(cashflows, historyReceipt, positionReceipt) {
  const observation = readMeteoraPositionReceipt(positionReceipt);
  const history = historyReceipt.history;
  if (observation.pool !== cashflows.target.pool || observation.position !== cashflows.target.position || observation.queriedUser !== cashflows.target.user) throw Error("POSITION_HISTORY_MISMATCH");
  if (history.events.some(event => event.tokenX !== observation.tokenX.mint || event.tokenY !== observation.tokenY.mint)) throw Error("POSITION_TOKEN_MISMATCH");
  const positionTime = Date.parse(observation.observedAt), historyTime = Date.parse(history.observedAt);
  const skew = (historyTime - positionTime) / 1000;
  const reasons = [];
  if (Math.abs(skew) > POSITION_VALUE_WINDOW_SECONDS) reasons.push("SNAPSHOT_WINDOW_EXCEEDED");
  if (history.events.some(event => event.blockTime * 1000 > positionTime)) reasons.push("EVENT_AFTER_POSITION_SNAPSHOT");
  if (observation.range.state === "UNKNOWN") reasons.push("POSITION_STATE_UNCONFIRMED");
  const sum = (a,b) => a === null || b === null ? null : a+b;
  const bx = decimalUnits(observation.tokenX.principalUsd), by = decimalUnits(observation.tokenY.principalUsd);
  const fx = decimalUnits(observation.tokenX.unclaimedFeeUsd), fy = decimalUnits(observation.tokenY.unclaimedFeeUsd);
  const balances = sum(bx,by), fees = sum(fx,fy);
  if (balances === null) reasons.push("POSITION_BALANCES_UNKNOWN");
  if (observation.range.state === "CLOSED" && [bx,by,fx,fy].some(v => v !== null && v !== 0n)) reasons.push("CLOSED_POSITION_COMPONENTS_NONZERO");
  // Aggregate cashflow strings may exceed the per-input 32-digit limit. They were
  // generated by the validated exact-arithmetic evaluator, so sum by fixed scale.
  const aggregateUnits = value => {
    if (typeof value !== "string" || !/^-?\d{1,36}(\.\d{1,18})?$/.test(value)) return null;
    const [whole,fraction=""] = value.replace(/^-/,"").split(".");
    const units=BigInt(whole)*10n**18n+BigInt(fraction.padEnd(18,"0"));
    return value.startsWith("-") ? -units : units;
  };
  const flows = aggregateUnits(cashflows.indexedCashflowBalanceUsd);
  const afterCosts = aggregateUnits(cashflows.indexedBalanceAfterEnteredCostsUsd);
  if (flows === null) reasons.push("INDEXED_CASHFLOWS_UNKNOWN");
  const eligible = reasons.length === 0;
  return {
    schema: "cofferhouse.liquidity.position-value-reference.v1", status: eligible ? "REFERENCE_ONLY" : "UNAVAILABLE",
    positionReceiptId: positionReceipt.receiptId, historyReceiptId: historyReceipt.receiptId,
    positionId: observation.id, tokenMints: { x: observation.tokenX.mint, y: observation.tokenY.mint },
    positionObservedAt: observation.observedAt, historyObservedAt: history.observedAt,
    snapshotSkewSeconds: skew, maxSnapshotSkewSeconds: POSITION_VALUE_WINDOW_SECONDS,
    providerBalanceComponentsUsd: { tokenX: decimalText(bx), tokenY: decimalText(by), total: decimalText(balances) },
    providerPendingFeeComponentsUsd: { tokenX: decimalText(fx), tokenY: decimalText(fy), total: decimalText(fees) },
    pendingFeesAdded: false, pendingRewardsAdded: false,
    balanceOnlyReferenceUsd: eligible ? decimalText(flows+balances) : null,
    balanceOnlyReferenceAfterEnteredCostsUsd: eligible && afterCosts !== null ? decimalText(afterCosts+balances) : null,
    reasons,
    warnings: ["PROVIDER_BALANCE_SEMANTICS_UNVERIFIED", "SNAPSHOTS_NOT_ATOMIC", "HISTORY_COMPLETENESS_UNVERIFIED", "PENDING_FEES_NOT_ADDED", "PENDING_REWARDS_NOT_INCLUDED", ...(fees === null ? ["PENDING_FEES_UNKNOWN"] : []), ...(afterCosts === null ? ["ADJUSTED_CASHFLOWS_UNAVAILABLE"] : [])],
    valuationVerified: false, sourceAuthenticated: false, realizedProfitUsd: null, netReturnPct: null,
    notice: "Reference = observed indexed cashflows + provider balanceTokenX/Y USD values, optionally minus entered external costs. Pending fees and rewards are not added because non-overlap is unverified. Retrieval timestamps within the reference window are not atomic state, historical valuation reconciliation or freshness guarantees. This is not realized profit, net PnL, a holding benchmark or investment return."
  };
}
